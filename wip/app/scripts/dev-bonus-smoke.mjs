import { chromium } from "@playwright/test";
import fs from "node:fs";
import { fresh, KEY, solutionCells, boardSignature } from "../core.js";
import { newAttempt } from "../powers.js";
const data = JSON.parse(fs.readFileSync("levels.json"));
const W = Number(process.argv[2] || 412), H = Number(process.argv[3] || 915), out = "reports/v4.2/dev/" + W;
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch({ args: ["--no-sandbox"] });
const page = await b.newPage({ viewport: { width: W, height: H }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
const errs = []; page.on("pageerror", (e) => errs.push(e.message)); page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const q = data.levels[4], s = { ...newAttempt(5), signature: boardSignature(q) }, sol = solutionCells(q); sol.slice(0, -1).forEach((i) => (s.cells[i] = 2));
await page.goto("http://127.0.0.1:8765/");
await page.evaluate(({ k, p }) => localStorage.setItem(k, JSON.stringify(p)), { k: KEY, p: { ...fresh(), nickname: "Seba", starterChosen: true, tutorialSeen: true, music: false, completed: [1, 2, 3, 4], sessions: { "pond-5": s } } });
await page.reload(); await page.waitForTimeout(500);
await page.locator('[data-action="continue"]').tap(); await page.waitForTimeout(300);
const r = await page.locator(`[data-cell="${sol.at(-1)}"]`).boundingBox();
await page.touchscreen.tap(r.x + 20, r.y + 20); await page.waitForTimeout(60); await page.touchscreen.tap(r.x + 20, r.y + 20);
await page.waitForTimeout(3500);
await page.getByRole("button", { name: "Next pond →" }).tap(); await page.waitForTimeout(400);
await page.screenshot({ path: out + "/1-offer.png" });
await page.getByRole("button", { name: "Play bonus" }).tap(); await page.waitForTimeout(400);
await page.screenshot({ path: out + "/2-controls.png" });
await page.getByRole("button", { name: "Got it" }).tap(); await page.waitForTimeout(300);
await page.screenshot({ path: out + "/3-play.png" });
const lv = JSON.parse(fs.readFileSync("crate-levels.json")).levels[0];
const key = { U: "ArrowUp", D: "ArrowDown", L: "ArrowLeft", R: "ArrowRight" };
for (const [k, ch] of [...lv.solution].entries()) { await page.keyboard.press(key[ch]); await page.waitForTimeout(140); if (k === 9) await page.screenshot({ path: out + "/4-mid.png" }); }
await page.waitForTimeout(400); await page.screenshot({ path: out + "/5-allpacked.png" });
await page.waitForTimeout(1200); await page.screenshot({ path: out + "/6-reward.png" });
await page.getByRole("button", { name: /Continue → Pond 6/ }).tap(); await page.waitForTimeout(500);
await page.screenshot({ path: out + "/7-pond6.png" });
console.log(JSON.stringify(await page.evaluate((k) => JSON.parse(localStorage.getItem(k)).bonus, KEY)), errs);
