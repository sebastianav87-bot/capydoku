#!/usr/bin/env python3
"""v4.2: verifies every bonus level with the Designer's approved solver (mockup/boxworld-concept/v3/verify/solver.py,
imported read-only) and writes crate-levels.json (app data) + reports/v4.2/crate-levels-solver.json."""
import json,sys,hashlib
if "--v42" not in sys.argv: raise SystemExit("v4.2 script: it REWRITES crate-levels.json with the v4.2 bonus levels. v4.3 uses scripts/verify-crate-levels-v43.py (read-only). Pass --v42 only on a v4.2 tree.")
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];V=Path('/workspace/capydoku/mockup/boxworld-concept/v3/verify')
sys.path.insert(0,str(V));import solver
LEVELS=[
 dict(id=1,name='Crate Cove 1',afterPond=5,rows=["#######","#.   .#","#  @  #","##$.$ #","#   $ #","###   #","#######"]),
 dict(id=2,name='Crate Cove 3',afterPond=15,rows=json.loads((V/'level.json').read_text())['rows'],source='Designer v3 verify/level.json (unchanged)'),
 dict(id=3,name='Crate Cove 5',afterPond=25,rows=["#########","#  . #  #","# .   # #","#. # $$ #","#       #","#    @  #","#  $ #  #","## #   ##","#########"]),
]
out=[];report=[]
for L in LEVELS:
 rows=L['rows'];walls,goals,boxes,player=solver.parse(rows);assert len(boxes)==len(goals)==3 and player
 mp,explored=solver.solve_moves(rows);assert mp,L['name']+' unsolvable'
 _,mpushes=solver.replay(rows,mp);pp,pmin,pmoves=solver.solve_pushes(rows);solver.replay(rows,pp)
 par=((len(mp)*4+2)//3+4)//5*5
 n=len(rows)-2
 out.append(dict(id=L['id'],name=L['name'],afterPond=L['afterPond'],n=n,rows=rows,fruit=['watermelon','banana','pear'],optimalMoves=len(mp),optimalPushes=pmin,pushesInMoveOptimal=mpushes,par=par,solution=mp.upper()))
 report.append(dict(id=L['id'],name=L['name'],afterPond=L['afterPond'],board=f'{n}x{n}',rocks=sum(r[1:-1].count('#') for r in rows[1:-1]),solvable=True,optimal_moves=len(mp),pushes_in_move_optimal=mpushes,optimal_pushes=pmin,moves_in_push_optimal=pmoves,states_explored_bfs=explored,move_optimal_solution=mp.upper(),push_optimal_solution=pp.upper(),par=par,source=L.get('source','generated by scripts/gen-crate-levels.mjs (seeded), picked by hand')))
 print(L['name'],n,'moves',len(mp),'pushes',mpushes,'opt pushes',pmin,'explored',explored,'par',par)
(ROOT/'crate-levels.json').write_text(json.dumps({'schema':1,'solver':'mockup/boxworld-concept/v3/verify/solver.py','solver_sha256':hashlib.sha256((V/'solver.py').read_bytes()).hexdigest(),'levels':out},indent=1)+'\n')
(ROOT/'reports/v4.2').mkdir(parents=True,exist_ok=True);(ROOT/'reports/v4.2/crate-levels-solver.json').write_text(json.dumps(report,indent=2)+'\n')
